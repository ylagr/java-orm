    @Test
    public void testOracle11RownumPagination() {
        // 1. 第一页：offset = 0, limit = 2 -> 经典 2 层嵌套 ROWNUM <= ?
        Query<Student> page1Query = orm.select(Student.class).page(1, 2);
        String sql1 = page1Query.toSql();
        SqlAndParams sp1 = page1Query.toSqlAndParams();
        System.out.println("Page 1 SQL: " + sql1);
        System.out.println("Page 1 Params: " + sp1.getParams());

        assertTrue(sql1.startsWith("SELECT * FROM (SELECT "));
        assertTrue(sql1.endsWith(") WHERE ROWNUM <= ?"));
        assertFalse(sql1.contains("OFFSET"));
        assertEquals(2, sp1.getParams().get(sp1.getParams().size() - 1));

        List<Student> page1 = page1Query.list();
        assertEquals(2, page1.size());
        assertEquals("Alice", page1.get(0).getStudentName());
        assertEquals("Bob", page1.get(1).getStudentName());

        // 2. 第二页：offset = 2, limit = 2 -> 经典 3 层嵌套 ROWNUM <= ? WHERE "row_num" > ?
        Query<Student> page2Query = orm.select(Student.class).page(2, 2);
        String sql2 = page2Query.toSql();
        SqlAndParams sp2 = page2Query.toSqlAndParams();
        System.out.println("Page 2 SQL: " + sql2);
        System.out.println("Page 2 Params: " + sp2.getParams());

        assertTrue(sql2.contains("ROWNUM AS \"row_num\""));
        assertTrue(sql2.contains("WHERE ROWNUM <= ?"));
        assertTrue(sql2.endsWith("WHERE \"row_num\" > ?"));
        // params: offset + limit = 4, then offset = 2
        int pSize = sp2.getParams().size();
        assertEquals(4, sp2.getParams().get(pSize - 2));
        assertEquals(2, sp2.getParams().get(pSize - 1));

        List<Student> page2 = page2Query.list();
        assertEquals(2, page2.size());
        assertEquals("Charlie", page2.get(0).getStudentName());
        assertEquals("David", page2.get(1).getStudentName());

        // 3. 仅 offset: offset = 3, limit = null
        Query<Student> offsetQuery = orm.select(Student.class).offset(3);
        String sql3 = offsetQuery.toSql();
        System.out.println("Offset Only SQL: " + sql3);
        assertTrue(sql3.contains("ROWNUM AS \"row_num\""));
        assertTrue(sql3.endsWith("WHERE \"row_num\" > ?"));
        List<Student> offsetList = offsetQuery.list();
        assertEquals(2, offsetList.size());
        assertEquals("David", offsetList.get(0).getStudentName());
        assertEquals("Eve", offsetList.get(1).getStudentName());
    }

    @Test
    public void testDynamicStringWhereConditions() {
        // 动态列名字符串: w.and("age").ge(24)
        List<Student> list1 = orm.select(Student.class)
                .where()
                .and("age").ge(24)
                .list();
        assertEquals(3, list1.size());

        // 动态表别名.列名: w.and("t0.age").lt(24)
        List<Student> list2 = orm.select(Student.class)
                .where()
                .and("t0.age").lt(24)
                .list();
        assertEquals(2, list2.size());

        // 实体属性名自动转列名: w.and("studentName").eq("Alice")
        List<Student> list3 = orm.select(Student.class)
                .where()
                .and("studentName").eq("Alice")
                .list();
        assertEquals(1, list3.size());
        assertEquals("Alice", list3.get(0).getStudentName());

        // 动态 or 条件与 between
        List<Student> list4 = orm.select(Student.class)
                .where()
                .and("age").between(20, 22)
                .or("student_name").eq("Eve")
                .list();
        assertEquals(3, list4.size());

        // 原生 SQL 条件: andRaw / orRaw
        List<Student> list5 = orm.select(Student.class)
                .where()
                .andRaw("\"age\" IN (?, ?)", 20, 26)
                .list();
        assertEquals(2, list5.size());
    }

    @Test
    public void testDynamicStringSelectGroupByOrderBy() {
        // select 传入列字符串与别名
        List<Map<String, Object>> maps = orm.select("id", "student_name as name", "age")
                .from(Student.class)
                .where()
                .and("age").ge(24)
                .orderBy("age").desc()
                .listMaps();
        assertEquals(3, maps.size());
        assertEquals(28, ((Number) maps.get(0).get("age")).intValue());
        assertEquals("Eve", maps.get(0).get("name"));

        // groupBy 传入字符串
        List<Map<String, Object>> groupMaps = orm.select(col("age"), count().as("cnt"))
                .from(Student.class)
                .groupBy("age")
                .orderBy("age").asc()
                .listMaps();
        assertEquals(5, groupMaps.size());

        // orderBy 传入字符串
        List<Student> ordered = orm.select(Student.class)
                .orderBy("student_name").asc()
                .list();
        assertEquals("Alice", ordered.get(0).getStudentName());
    }

    @Test
    public void testDynamicStringUpdateAndDelete() {
        // update.set("age", 99)
        int updated = orm.update(Student.class)
                .set("age", 99)
                .where()
                .and("student_name").eq("Alice")
                .execute();
        assertEquals(1, updated);

        Student alice = orm.select(Student.class)
                .where()
                .and("student_name").eq("Alice")
                .single();
        assertNotNull(alice);
        assertEquals(99, alice.getAge().intValue());

        // update.set("student_name", "BobUpdated")
        orm.update(Student.class)
                .set("student_name", "BobUpdated")
                .where()
                .and("age").eq(22)
                .execute();

        Student bob = orm.select(Student.class)
                .where()
                .and("age").eq(22)
                .single();
        assertNotNull(bob);
        assertEquals("BobUpdated", bob.getStudentName());

        // delete 动态条件
        int deleted = orm.delete(Student.class)
                .where()
                .and("student_name").eq("Eve")
                .execute();
        assertEquals(1, deleted);

        Student eve = orm.select(Student.class)
                .where()
                .and("student_name").eq("Eve")
                .single();
        assertNull(eve);
    }

    @Test
    public void testToSqlAndParamsAtAnyStage() {
        // Query 阶段
        Query<Student> q = orm.select(Student.class);
        String sql1 = q.toSql();
        assertNotNull(sql1);
        assertTrue(sql1.contains("FROM \"t_student\""));
        assertEquals(sql1, q.toString());

        // WhereBuilder 阶段
        WhereBuilder<Student> w = q.where().and("age").ge(20);
        String sql2 = w.toSql();
        SqlAndParams sp2 = w.toSqlAndParams();
        assertTrue(sql2.contains("WHERE"));
        assertTrue(sql2.contains("\"age\" >= ?"));
        assertEquals(20, sp2.getParams().get(sp2.getParams().size() - 1));
        assertEquals(sql2, w.toString());

        // UpdateBuilder 阶段
        com.javaorm.core.mutation.UpdateBuilder<Student> u = orm.update(Student.class).set("age", 30);
        String uSql1 = u.toSql();
        assertTrue(uSql1.startsWith("UPDATE \"t_student\" SET \"age\" = ?"));
        assertEquals(uSql1, u.toString());
        WhereBuilder<Student> uWhere = u.where().and("id").eq(1);
        String uSql2 = uWhere.toSql();
        assertTrue(uSql2.contains("WHERE"));
        assertEquals(uSql2, uWhere.toString());

        // DeleteBuilder 阶段
        com.javaorm.core.mutation.DeleteBuilder<Student> d = orm.delete(Student.class);
        String dSql1 = d.toSql();
        // 存在逻辑删除，因此渲染为 UPDATE is_deleted = 1
        assertTrue(dSql1.contains("UPDATE \"t_student\" SET \"is_deleted\" = ?"));
        assertEquals(dSql1, d.toString());
        WhereBuilder<Student> dWhere = d.where().and("id").eq(1);
        String dSql2 = dWhere.toSql();
        assertTrue(dSql2.contains("WHERE"));
        assertEquals(dSql2, dWhere.toString());

        // DtoQuery 阶段
        DtoQuery<StudentWindowDto, Student> dtoQ = orm.select(StudentWindowDto.class)
                .from(Student.class)
                .select("id", "student_name");
        String dtoSql1 = dtoQ.toSql();
        assertTrue(dtoSql1.contains("SELECT"));
        assertEquals(dtoSql1, dtoQ.toString());
        WhereBuilder<Student> dtoWhere = dtoQ.where().and("age").ge(20);
        String dtoSql2 = dtoWhere.toSql();
        assertTrue(dtoSql2.contains("WHERE"));
        assertEquals(dtoSql2, dtoWhere.toString());
    }

    @Test
    public void testChainedPrintSql() {
        // 1. 全局配置为 false，但链式指定 printSql(true)，强制打印
        assertFalse(config.isPrintSql());
        Query<Student> q1 = orm.select(Student.class).printSql(true);
        assertTrue(q1.getEffectiveConfig().isPrintSql());
        List<Student> list1 = q1.where().and("age").gt(18).list();
        assertEquals(5, list1.size());

        // 2. 链式指定 printSql(false)，强制不打印
        Query<Student> q2 = orm.select(Student.class).printSql(false);
        assertFalse(q2.getEffectiveConfig().isPrintSql());

        // 3. 链式指定 printSql()，遵从当前全局配置（当前配置为 false）
        Query<Student> q3 = orm.select(Student.class).printSql();
        assertFalse(q3.getEffectiveConfig().isPrintSql());

        // 4. 将全局配置改为 true
        config.setPrintSql(true);
        Query<Student> q4 = orm.select(Student.class).printSql();
        assertTrue(q4.getEffectiveConfig().isPrintSql());

        // 5. 在 WhereBuilder 上链式调用 printSql(false)
        WhereBuilder<Student> w = orm.select(Student.class).where().and("age").gt(18).printSql(false);
        assertEquals(5, w.list().size());

        // 6. 在 UpdateBuilder 和 DeleteBuilder 上链式调用
        int uCount = orm.update(Student.class).set("age", 25).where().and("id").eq(1).printSql(true).execute();
        assertEquals(1, uCount);

        int dCount = orm.delete(Student.class).where().and("id").eq(9999).printSql(true).execute();
        assertEquals(0, dCount);
    }

    @Test
    public void testTableAliasResetPerSql() {
        Student s = orm.proxy(Student.class);
        Teacher t = orm.proxy(Teacher.class);

        // 1. 连续独立查询，每次的根表别名都必须从 t0 开始
        for (int i = 0; i < 5; i++) {
            WhereBuilder<Student> q = orm.select(Student.class).where().and(s.getAge()).ge(18);
            String sql = q.toSql();
            assertTrue("Query " + i + " should use t0 as root alias, but got: " + sql,
                    sql.contains("FROM \"t_student\" t0") || sql.contains("FROM (SELECT t0."));
            assertEquals("t0", q.getStatement().getRootTableAlias());
            List<Student> list = q.list();
            assertFalse(list.isEmpty());
        }

        // 2. 带有 JOIN 的查询：内部表别名从 0 开始连续递增 (t0, t1)，下一次查询恢复从 t0 开始
        WhereBuilder<Student> joinQuery = orm.select(Student.class)
                .where()
                .and(s.getTeacher().getAge()).gt(30);
        String joinSql = joinQuery.toSql();
        assertTrue(joinSql.contains("FROM \"t_student\" t0"));
        assertTrue(joinSql.contains("JOIN \"t_teacher\" t1"));
        joinQuery.list();

        // 之后的查询必须再次从 t0 开始
        WhereBuilder<Student> afterJoin = orm.select(Student.class).where().and(s.getAge()).ge(20);
        assertEquals("t0", afterJoin.getStatement().getRootTableAlias());
        assertTrue(afterJoin.toSql().contains("FROM \"t_student\" t0"));

        // 3. 带有子查询的语句：内部表别名从 0 开始计算 (t0, t1)，下一次查询恢复从 t0 开始
        WhereBuilder<Student> subQuery = orm.select(Student.class)
                .where()
                .andExists(
                        orm.select(t.getId())
                                .from(Teacher.class)
                                .where()
                                .and(t.getId()).eq(s.getTeacherId())
                );
        String subSql = subQuery.toSql();
        assertTrue(subSql.contains("FROM \"t_student\" t0"));
        assertTrue(subSql.contains("FROM \"t_teacher\" t1"));
        assertTrue(subSql.contains("t1.\"id\" = t0.\"teacher_id\""));

        // 之后的查询必须再次从 t0 开始
        WhereBuilder<Teacher> afterSub = orm.select(Teacher.class).where().and(t.getAge()).ge(30);
        assertEquals("t0", afterSub.getStatement().getRootTableAlias());
        assertTrue(afterSub.toSql().contains("FROM \"t_teacher\" t0"));

        // 4. Update 和 Delete 之后，新查询同样从 t0 开始
        orm.update(Student.class).set(s.getAge(), 20).where().and(s.getId()).eq(1).execute();
        Query<Student> afterUpdate = orm.select(Student.class);
        assertEquals("t0", afterUpdate.getStatement().getRootTableAlias());

        orm.delete(Student.class).where().and(s.getId()).eq(99999).execute();
        Query<Student> afterDelete = orm.select(Student.class);
        assertEquals("t0", afterDelete.getStatement().getRootTableAlias());
    }
