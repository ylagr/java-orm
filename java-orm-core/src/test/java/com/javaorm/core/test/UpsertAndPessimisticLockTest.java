    // ==========================================
    // 1. 悲观锁 SQL 生成与降级测试
    // ==========================================

    @Test
    public void testPessimisticLockSqlDialects() {
        // MySQL 8.0+
        Dialect mysql = new MySQLDialect();
        String sqlMy1 = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdate().toSql(mysql);
        assertTrue(sqlMy1.endsWith("FOR UPDATE"));

        String sqlMyNowait = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdateNowait().toSql(mysql);
        assertTrue(sqlMyNowait.endsWith("FOR UPDATE NOWAIT"));

        String sqlMySkip = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdateSkipLocked().toSql(mysql);
        assertTrue(sqlMySkip.endsWith("FOR UPDATE SKIP LOCKED"));

        // PostgreSQL
        Dialect pg = new PostgreSQLDialect();
        String sqlPg1 = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdate().toSql(pg);
        assertTrue(sqlPg1.endsWith("FOR UPDATE"));

        String sqlPgNowait = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdateNowait().toSql(pg);
        assertTrue(sqlPgNowait.endsWith("FOR UPDATE NOWAIT"));

        String sqlPgSkip = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdateSkipLocked().toSql(pg);
        assertTrue(sqlPgSkip.endsWith("FOR UPDATE SKIP LOCKED"));

        // H2 (NOWAIT 与 SKIP LOCKED 安全降级为 FOR UPDATE)
        Dialect h2 = new H2Dialect();
        String sqlH2Nowait = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdateNowait().toSql(h2);
        assertTrue(sqlH2Nowait.endsWith("FOR UPDATE"));
        assertFalse(sqlH2Nowait.contains("NOWAIT"));

        // SQLite (退化为无锁，避免不支持行锁报错)
        Dialect sqlite = new SQLiteDialect();
        String sqlSqlite = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdate().toSql(sqlite);
        assertFalse(sqlSqlite.contains("FOR UPDATE"));

        // Oracle
        Dialect oracle = new OracleDialect();
        String sqlOraNowait = orm.select(UpsertAccount.class).where().eq(UpsertAccount::getId, 1L).forUpdateNowait().toSql(oracle);
        assertTrue(sqlOraNowait.endsWith("FOR UPDATE NOWAIT"));
    }

    @Test
    public void testPessimisticLockExecutionInH2() {
        // 先插入一条记录
        UpsertAccount acc = new UpsertAccount();
        acc.setUserCode("U001");
        acc.setUserName("Alice");
        acc.setBalance(100.0);
        acc.setCreateTime("2026-11-19 12:00:00");
        orm.insert(acc);
        assertNotNull(acc.getId());

        // 使用 forUpdate() 在 H2 中查询
        UpsertAccount locked = orm.select(UpsertAccount.class)
                .where().eq(UpsertAccount::getId, acc.getId())
                .forUpdate()
                .first();

        assertNotNull(locked);
        assertEquals("Alice", locked.getUserName());
    }

    // ==========================================
    // 2. 跨方言 UPSERT SQL 生成测试
    // ==========================================

    @Test
    public void testUpsertSqlDialects() {
        UpsertAccount acc = new UpsertAccount();
        acc.setId(10L);
        acc.setUserCode("U002");
        acc.setUserName("Bob");
        acc.setBalance(200.0);
        acc.setCreateTime("2026-11-19 12:00:00");

        // MySQL
        Dialect mysql = new MySQLDialect();
        String sqlMysql = orm.insertOrUpdateable(acc).toSql(mysql);
        assertTrue(sqlMysql.contains("INSERT INTO `test_upsert_account`"));
        assertTrue(sqlMysql.contains("ON DUPLICATE KEY UPDATE"));
        assertTrue(sqlMysql.contains("`user_name` = VALUES(`user_name`)"));
        // 验证默认忽略创建时间字段
        assertFalse(sqlMysql.contains("`create_time` = VALUES(`create_time`)"));

        // PostgreSQL
        Dialect pg = new PostgreSQLDialect();
        String sqlPg = orm.insertOrUpdateable(acc).toSql(pg);
        assertTrue(sqlPg.contains("INSERT INTO \"test_upsert_account\""));
        assertTrue(sqlPg.contains("ON CONFLICT (\"id\") DO UPDATE SET"));
        assertTrue(sqlPg.contains("\"user_name\" = EXCLUDED.\"user_name\""));

        // Oracle MERGE INTO
        Dialect oracle = new OracleDialect();
        String sqlOracle = orm.insertOrUpdateable(acc).toSql(oracle);
        assertTrue(sqlOracle.startsWith("MERGE INTO"));
        assertTrue(sqlOracle.contains("USING (SELECT"));
        assertTrue(sqlOracle.contains("WHEN MATCHED THEN UPDATE SET"));
        assertTrue(sqlOracle.contains("WHEN NOT MATCHED THEN INSERT"));

        // DO NOTHING 模式测试
        String sqlPgNothing = orm.insertOrUpdateable(acc).doNothing().toSql(pg);
        assertTrue(sqlPgNothing.contains("ON CONFLICT (\"id\") DO NOTHING"));

        String sqlMyNothing = orm.insertOrUpdateable(acc).doNothing().toSql(mysql);
        assertTrue(sqlMyNothing.contains("ON DUPLICATE KEY UPDATE `id` = `id`"));

        // 指定 onConflict 唯一列测试（如 user_code）
        String sqlPgConflictCode = orm.insertOrUpdateable(acc)
                .onConflict(a -> a.getUserCode())
                .updateColumns(a -> a.getBalance())
                .toSql(pg);
        assertTrue(sqlPgConflictCode.contains("ON CONFLICT (\"user_code\") DO UPDATE SET \"balance\" = EXCLUDED.\"balance\""));
        assertFalse(sqlPgConflictCode.contains("\"user_name\" = EXCLUDED.\"user_name\""));
    }

    // ==========================================
    // 3. 真实 H2 数据库 UPSERT 落库与幂等测试
    // ==========================================

    @Test
    public void testUpsertInsertThenUpdateInDatabase() {
        // 1. 首次 UPSERT (不存在 -> 执行 INSERT)
        UpsertAccount acc = new UpsertAccount();
        acc.setId(100L);
        acc.setUserCode("U100");
        acc.setUserName("Charlie");
        acc.setBalance(500.0);
        acc.setCreateTime("2026-11-19 15:00:00");

        int rows1 = orm.insertOrUpdate(acc);
        assertEquals(1, rows1);

        UpsertAccount dbAcc1 = orm.findById(UpsertAccount.class, 100L);
        assertNotNull(dbAcc1);
        assertEquals("Charlie", dbAcc1.getUserName());
        assertEquals(Double.valueOf(500.0), dbAcc1.getBalance());
        assertEquals("2026-11-19 15:00:00", dbAcc1.getCreateTime());

        // 2. 二次 UPSERT (已存在 -> 执行 UPDATE)，修改姓名和余额
        acc.setUserName("Charlie Modified");
        acc.setBalance(888.0);

        int rows2 = orm.insertOrUpdate(acc);
        assertEquals(1, rows2);

        UpsertAccount dbAcc2 = orm.findById(UpsertAccount.class, 100L);
        assertNotNull(dbAcc2);
        assertEquals("Charlie Modified", dbAcc2.getUserName());
        assertEquals(Double.valueOf(888.0), dbAcc2.getBalance());
    }

    @Test
    public void testUpsertDoNothingInDatabase() {
        UpsertAccount acc = new UpsertAccount();
        acc.setId(200L);
        acc.setUserCode("U200");
        acc.setUserName("David");
        acc.setBalance(300.0);
        orm.insert(acc);

        // 存在冲突时 DO NOTHING
        acc.setUserName("David Changed");
        acc.setBalance(999.0);
        orm.insertOrUpdateable(acc).doNothing().execute();

        UpsertAccount dbAcc = orm.findById(UpsertAccount.class, 200L);
        assertEquals("David", dbAcc.getUserName());
        assertEquals(Double.valueOf(300.0), dbAcc.getBalance());
    }

    @Test
    public void testBatchUpsertInDatabase() {
        // 先插入一条记录
        UpsertAccount acc1 = new UpsertAccount();
        acc1.setId(301L);
        acc1.setUserCode("U301");
        acc1.setUserName("Old 301");
        acc1.setBalance(10.0);
        orm.insert(acc1);

        // 准备批处理列表：acc1 (需更新) + acc2 (需插入)
        UpsertAccount u1 = new UpsertAccount();
        u1.setId(301L);
        u1.setUserCode("U301");
        u1.setUserName("New 301");
        u1.setBalance(99.0);

        UpsertAccount u2 = new UpsertAccount();
        u2.setId(302L);
        u2.setUserCode("U302");
        u2.setUserName("New 302");
        u2.setBalance(200.0);

        int affected = orm.insertOrUpdate(Arrays.asList(u1, u2));
        assertTrue(affected >= 2);

        UpsertAccount db1 = orm.findById(UpsertAccount.class, 301L);
        assertNotNull(db1);
        assertEquals("New 301", db1.getUserName());
        assertEquals(Double.valueOf(99.0), db1.getBalance());

        UpsertAccount db2 = orm.findById(UpsertAccount.class, 302L);
        assertNotNull(db2);
        assertEquals("New 302", db2.getUserName());
        assertEquals(Double.valueOf(200.0), db2.getBalance());
    }
