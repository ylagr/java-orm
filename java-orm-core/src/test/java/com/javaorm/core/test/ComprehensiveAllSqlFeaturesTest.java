    @Test
    public void testSqlDialectSwappabilityAcrossAllDatabases() {
        Student s = orm.proxy(Student.class);

        // 构造一个包含聚合、开窗函数、字符串函数、日期函数、数学函数、空值函数、CASE WHEN、关联JOIN与子查询的复杂 Java SQL AST
        SelectBuilder<Student> query = orm.select(Student.class)
                .select(
                        s.getId(),
                        s.getStudentName(),
                        count().as("total"),
                        rowNumber().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rn"),
                        concat(s.getStudentName(), "_", s.getAge()).as("full_info"),
                        subString(s.getStudentName(), 1, 2).as("sub_name"),
                        left(s.getStudentName(), 1).as("first_char"),
                        right(s.getStudentName(), 1).as("last_char"),
                        instr(s.getStudentName(), "明").as("has_ming"),
                        mod(s.getAge(), 5).as("age_mod"),
                        year(s.getCreateTime()).as("c_year"),
                        month(s.getCreateTime()).as("c_month"),
                        day(s.getCreateTime()).as("c_day"),
                        hour(s.getCreateTime()).as("c_hour"),
                        minute(s.getCreateTime()).as("c_min"),
                        second(s.getCreateTime()).as("c_sec"),
                        now().as("cur_time"),
                        curDate().as("cur_date"),
                        ifNull(s.getAge(), 0).as("effective_age"),
                        nullIf(s.getAge(), 100).as("null_if_100"),
                        caseWhen(s.getAge(), SqlOperator.GE, 18, "ADULT")
                                .elseVal("MINOR")
                                .as("status")
                )
                .where().and(s.getAge()).gt(15)
                .page(2, 10);

        // 1. 测试 SQLite 方言
        Dialect sqliteDialect = new SQLiteDialect();
        SqlAndParams sqliteSql = sqliteDialect.buildSelect(query.getStatement());
        assertNotNull(sqliteSql.getSql());
        assertTrue(sqliteSql.getSql().contains(" || "));
        assertTrue(sqliteSql.getSql().contains("strftime('%Y'"));
        assertTrue(sqliteSql.getSql().contains("substr("));
        assertTrue(sqliteSql.getSql().contains(" % "));
        assertTrue(sqliteSql.getSql().contains("LIMIT ? OFFSET ?"));

        // 2. 测试 MySQL 方言
        Dialect mySqlDialect = new MySQLDialect();
        SqlAndParams mysqlSql = mySqlDialect.buildSelect(query.getStatement());
        assertNotNull(mysqlSql.getSql());
        assertTrue(mysqlSql.getSql().contains("CONCAT("));
        assertTrue(mysqlSql.getSql().contains("YEAR("));
        assertTrue(mysqlSql.getSql().contains("IFNULL("));
        assertTrue(mysqlSql.getSql().contains("LIMIT ? OFFSET ?"));

        // 3. 测试 PostgreSQL 方言
        Dialect pgDialect = new PostgreSQLDialect();
        SqlAndParams pgSql = pgDialect.buildSelect(query.getStatement());
        assertNotNull(pgSql.getSql());
        assertTrue(pgSql.getSql().contains("COALESCE("));
        assertTrue(pgSql.getSql().contains("EXTRACT(YEAR FROM"));
        assertTrue(pgSql.getSql().contains("EXTRACT(MINUTE FROM"));
        assertTrue(pgSql.getSql().contains("STRPOS("));
        assertTrue(pgSql.getSql().contains("LIMIT ? OFFSET ?"));

        // 4. 测试 Oracle 12c+ 方言
        Dialect oracleDialect = new OracleDialect();
        SqlAndParams oracleSql = oracleDialect.buildSelect(query.getStatement());
        assertNotNull(oracleSql.getSql());
        assertTrue(oracleSql.getSql().contains("NVL("));
        assertTrue(oracleSql.getSql().contains(" || "));
        assertTrue(oracleSql.getSql().contains("EXTRACT(YEAR FROM"));
        assertTrue(oracleSql.getSql().contains("EXTRACT(HOUR FROM CAST("));
        assertTrue(oracleSql.getSql().contains("OFFSET ? ROWS FETCH NEXT ? ROWS ONLY"));

        // 5. 测试 Oracle 11g 方言 (经典 ROWNUM 嵌套分页)
        Dialect oracle11Dialect = new Oracle11Dialect();
        SqlAndParams oracle11Sql = oracle11Dialect.buildSelect(query.getStatement());
        assertNotNull(oracle11Sql.getSql());
        assertTrue(oracle11Sql.getSql().contains("ROWNUM AS \"row_num\""));
        assertTrue(oracle11Sql.getSql().contains("WHERE \"row_num\" > ?"));

        // 6. 测试 H2 方言
        Dialect h2Dialect = new H2Dialect();
        SqlAndParams h2Sql = h2Dialect.buildSelect(query.getStatement());
        assertNotNull(h2Sql.getSql());
        assertTrue(h2Sql.getSql().contains("LIMIT ? OFFSET ?"));
    }
