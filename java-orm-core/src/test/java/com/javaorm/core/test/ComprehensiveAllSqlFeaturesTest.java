    @Test
    public void testMultiLevelIncludesManyToOneWithFiltersAtEachLevel() {
        Student s = orm.proxy(Student.class);

        // 从 Student 查起，两层 ManyToOne: Student -> Teacher -> School
        // 筛选：Teacher 年龄 >= 35，School 城市为 '北京'
        List<Student> students = orm.select(Student.class)
                .include(s.getTeacher(), (SelectBuilder<Teacher> tQuery, Teacher t) -> {
                    tQuery.where().and(t.getAge()).ge(35);
                    tQuery.include(t.getSchool(), (SelectBuilder<School> schQuery, School sch) -> {
                        schQuery.where().and(sch.getCity()).eq("北京");
                    });
                })
                .orderBy(s.getId()).asc()
                .list();

        assertNotNull(students);
        assertEquals(5, students.size());

        // 小明 (teacherId=1, 张教授 age=45, 清华大学 city='北京'): teacher 和 school 都应装配成功
        Student s1 = students.get(0);
        assertNotNull(s1.getTeacher());
        assertEquals("张教授", s1.getTeacher().getTeacherName());
        assertNotNull(s1.getTeacher().getSchool());
        assertEquals("清华大学", s1.getTeacher().getSchool().getSchoolName());

        // 小刚 (teacherId=2, 李副教授 age=32 < 35 被过滤掉): teacher 应为 null
        Student s3 = students.get(2);
        assertNull(s3.getTeacher());

        // 小李 (teacherId=3, 王教授 age=50, 复旦大学 city='上海' != '北京'): teacher 存在但 school 为 null
        Student s5 = students.get(4);
        assertNotNull(s5.getTeacher());
        assertEquals("王教授", s5.getTeacher().getTeacherName());
        assertNull(s5.getTeacher().getSchool());
    }

    @Test
    public void testMultiLevelIncludesOneToManyWithFiltersAtEachLevel() {
        School sch = orm.proxy(School.class);

        // 从 School 查起，两层 OneToMany: School -> Teachers -> Students
        // 筛选：Teacher 年龄 >= 30, Student 年龄 >= 20
        List<School> schools = orm.select(School.class)
                .include(sch.getTeachers(), (SelectBuilder<Teacher> tQuery, Teacher t) -> {
                    tQuery.where().and(t.getAge()).ge(30);
                    tQuery.orderBy(t.getAge()).desc();
                    tQuery.include(t.getStudents(), (SelectBuilder<Student> stQuery, Student st) -> {
                        stQuery.where().and(st.getAge()).ge(20);
                        stQuery.orderBy(st.getAge()).asc();
                    });
                })
                .where().and(sch.getId()).eq(1L)
                .list();

        assertNotNull(schools);
        assertEquals(1, schools.size());
        School s1 = schools.get(0);
        assertEquals("清华大学", s1.getSchoolName());
        assertNotNull(s1.getTeachers());

        // 清华有两个老师：张教授 (45岁 >= 30) 和 李副教授 (32岁 >= 30)
        assertEquals(2, s1.getTeachers().size());
        Teacher tZhang = s1.getTeachers().get(0);
        assertEquals("张教授", tZhang.getTeacherName());

        // 张教授的学生有小明 (18岁 < 20 被过滤) 和 小红 (22岁 >= 20) -> 只保留小红
        assertNotNull(tZhang.getStudents());
        assertEquals(1, tZhang.getStudents().size());
        assertEquals("小红", tZhang.getStudents().get(0).getStudentName());
    }

