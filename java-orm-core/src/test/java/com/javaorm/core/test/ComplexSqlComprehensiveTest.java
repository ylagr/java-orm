    @Test
    public void testComplexDeleteWithNestedGroupsAndSubquery() {
        // 先插入两名用于删除测试的学生
        insertStudent("DEL_TARGET_1", 99, 1L, 0); // 属于张教授
        insertStudent("DEL_TARGET_2", 99, null, 0); // 无导师

        Student s = orm.proxy(Student.class);
        Teacher t = orm.proxy(Teacher.class);

        // 逻辑删除年龄 >= 90 且无导师的学生
        int deleted = orm.delete(Student.class)
                .where((w, stu) -> w
                        .andGroup((g, st) -> g
                                .and(st.getAge()).ge(90)
                                .and(st.getStudentName()).like("DEL_%")
                        )
                        .andNotExists(
                                orm.select(t.getId())
                                   .from(Teacher.class)
                                   .where()
                                       .and(t.getId()).eq(stu.getTeacherId())
                        )
                ).execute();

        assertEquals(1, deleted); // 仅 DEL_TARGET_2 被删除

        // 正常查询无法查出已删除的学生
        Student d2 = orm.select(Student.class).where().and(s.getStudentName()).eq("DEL_TARGET_2").single();
        assertNull(d2);

        // DEL_TARGET_1 有导师，未被删除
        Student d1 = orm.select(Student.class).where().and(s.getStudentName()).eq("DEL_TARGET_1").single();
        assertNotNull(d1);
    }

    /**
     * 7. 全部 10 种开窗函数复合投影与结果断言
     */
    @Test
    public void testAllTenWindowFunctionsCombined() {
        Student s = orm.proxy(Student.class);

        List<Map<String, Object>> rows = orm.select(
                s.getId(),
                s.getStudentName(),
                s.getAge(),
                rowNumber().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rn"),
                rank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rk"),
                denseRank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("drk"),
                ntile(2).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("nt"),
                percentRank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("pr"),
                cumeDist().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("cd"),
                sum(s.getAge()).over().partitionBy(s.getTeacherId()).as("sum_age"),
                avg(s.getAge()).over().partitionBy(s.getTeacherId()).as("avg_age"),
                lead(s.getAge(), 1, 0).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("next_age"),
                lag(s.getAge(), 1, 0).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("prev_age"),
                firstValue(s.getAge()).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("first_age")
        ).from(Student.class)
         .where()
             .and(s.getTeacherId()).eq(1L)
         .orderBy(s.getAge()).asc()
         .listMaps();

        // Teacher 1 组共 3 名未删除学生: 学生A(20), 学生B(22), 学生C(24)
        assertEquals(3, rows.size());

        // 行 1: 学生A (20岁)
        Map<String, Object> r1 = rows.get(0);
        assertEquals(1L, ((Number) r1.get("rn")).longValue());
        assertEquals(1L, ((Number) r1.get("rk")).longValue());
        assertEquals(0, ((Number) r1.get("prev_age")).intValue()); // lag 默认 0
        assertEquals(22, ((Number) r1.get("next_age")).intValue()); // lead 是 22
        assertEquals(20, ((Number) r1.get("first_age")).intValue());

        // 行 3: 学生C (24岁)
        Map<String, Object> r3 = rows.get(2);
        assertEquals(3L, ((Number) r3.get("rn")).longValue());
        assertEquals(22, ((Number) r3.get("prev_age")).intValue());
        assertEquals(0, ((Number) r3.get("next_age")).intValue()); // 已经是最后一条
        assertEquals(66, ((Number) r3.get("sum_age")).intValue()); // 20 + 22 + 24 = 66
    }

