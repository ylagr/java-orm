    public void testSubqueryInSelectProjection() {
        Student s = orm.proxy(Student.class);
        Teacher t = orm.proxy(Teacher.class);

        List<Map<String, Object>> rows = orm.select(
                s.getId(),
                s.getStudentName(),
                subQuery(
                        orm.select(t.getTeacherName())
                           .from(Teacher.class)
                           .where()
                               .and(t.getId()).eq(s.getTeacherId())
                ).as("mentor_name")
        ).from(Student.class)
         .where()
             .and(s.getTeacherId()).isNotNull()
             .and(s.getAge()).le(20)
         .orderBy(s.getId()).asc()
         .listMaps();

        // 年龄 <= 20 且有导师的学生: 学生A(20岁, 导师张教授) 和 学生D(19岁, 导师李副教授)
        assertEquals(2, rows.size());

        Map<String, Object> r1 = rows.get(0);
        assertEquals("学生A", r1.get("student_name"));
        assertEquals("张教授", r1.get("mentor_name"));

        Map<String, Object> r2 = rows.get(1);
        assertEquals("学生D", r2.get("student_name"));
        assertEquals("李副教授", r2.get("mentor_name"));
    }

    /**
     * 10. 跨方言复杂分页 SQL 语法精准生成对比（SQLite vs Oracle 11g vs Oracle 12c+）
     */
    @Test
    public void testMultiDialectComplexPagingSqlGeneration() {
        Student s = orm.proxy(Student.class);

        // 构建基准复杂查询
        Query<Student> query = orm.select(Student.class);
        query.where()
                .and(s.getAge()).gt(18)
                .andGroup((g, stu) -> g
                        .and(stu.getStudentName()).like("学生%")
                        .or(stu.getTeacher().getAge()).ge(30)
                )
             .orderBy(s.getAge()).desc()
             .orderBy(s.getId()).asc();

        // 统一分页参数：第 2 页，每页 3 条（offset = 3, limit = 3）
        query.page(2, 3);

        // 10.1 SQLite 方言验证
        SQLiteDialect sqliteDialect = new SQLiteDialect();
        SqlAndParams sqliteSql = sqliteDialect.buildSelect(query.getStatement());
        assertTrue("SQLite must use LIMIT ? OFFSET ?", sqliteSql.getSql().contains("LIMIT ? OFFSET ?"));
        assertEquals(3, sqliteSql.getParams().get(sqliteSql.getParams().size() - 2)); // limit = 3
        assertEquals(3, sqliteSql.getParams().get(sqliteSql.getParams().size() - 1)); // offset = 3

        // 10.2 Oracle 11g 方言验证（ROWNUM 双层包裹）
        Oracle11Dialect oracle11Dialect = new Oracle11Dialect();
        SqlAndParams oracle11Sql = oracle11Dialect.buildSelect(query.getStatement());
        assertTrue("Oracle 11g must wrap with ROWNUM subquery", oracle11Sql.getSql().contains("ROWNUM AS \"row_num\""));
        assertTrue(oracle11Sql.getSql().contains("WHERE ROWNUM <= ?"));
        assertTrue(oracle11Sql.getSql().endsWith("WHERE \"row_num\" > ?"));
        assertEquals(6, oracle11Sql.getParams().get(oracle11Sql.getParams().size() - 2)); // offset + limit = 6
        assertEquals(3, oracle11Sql.getParams().get(oracle11Sql.getParams().size() - 1)); // offset = 3

        // 10.3 Oracle 12c+ 方言验证（OFFSET-FETCH 现代化标准语法）
        OracleDialect oracle12Dialect = new OracleDialect();
        SqlAndParams oracle12Sql = oracle12Dialect.buildSelect(query.getStatement());
        assertTrue("Oracle 12c+ must use OFFSET ? ROWS FETCH NEXT ? ROWS ONLY",
                oracle12Sql.getSql().contains("OFFSET ? ROWS FETCH NEXT ? ROWS ONLY"));
        assertEquals(3, oracle12Sql.getParams().get(oracle12Sql.getParams().size() - 2)); // offset = 3
        assertEquals(3, oracle12Sql.getParams().get(oracle12Sql.getParams().size() - 1)); // limit = 3
    }

    /**
     * 11. 边界条件全排列与操作符组合测试（单元素 IN、全模式 LIKE、BETWEEN、IS NULL）
     */
    @Test
    public void testEdgeCaseConditionPermutations() {
        Student s = orm.proxy(Student.class);

        // 单元素 IN 与 NOT IN
        List<Student> inList = orm.select(Student.class)
                .where()
                    .and(s.getId()).in(Collections.singletonList(1L))
                .list();
        assertEquals(1, inList.size());
        assertEquals("学生A", inList.get(0).getStudentName());

        List<Student> notInList = orm.select(Student.class)
                .where()
                    .and(s.getId()).notIn(Arrays.asList(1L, 2L, 3L, 4L, 5L, 6L))
                .list();
        assertEquals(1, notInList.size());
        assertEquals("学生G", notInList.get(0).getStudentName()); // 仅学生G未被排除

        // 各种 LIKE 模式匹配
        List<Student> likeLeft = orm.select(Student.class).where().and(s.getStudentName()).likeLeft("A").list();
        assertEquals(1, likeLeft.size()); // "%A" -> 学生A

        List<Student> likeRight = orm.select(Student.class).where().and(s.getStudentName()).likeRight("学生").list();
        assertEquals(7, likeRight.size()); // "学生%" -> 全部 7 名未删除学生

        List<Student> likeAll = orm.select(Student.class).where().and(s.getStudentName()).likeAll("生").list();
        assertEquals(7, likeAll.size()); // "%生%"

        List<Student> notLike = orm.select(Student.class).where().and(s.getStudentName()).notLike("%A").list();
        assertEquals(6, notLike.size()); // 排除学生A

        // IS NULL 和 IS NOT NULL
        List<Student> nullTeacher = orm.select(Student.class).where().and(s.getTeacherId()).isNull().list();
        assertEquals(1, nullTeacher.size());
        assertEquals("学生G", nullTeacher.get(0).getStudentName());

        List<Student> notNullTeacher = orm.select(Student.class).where().and(s.getTeacherId()).isNotNull().list();
        assertEquals(6, notNullTeacher.size());
    }

