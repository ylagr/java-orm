    /**
     * 1. 超复杂全语法融合查询（Kitchen Sink Query）
     * 涵盖：SELECT 投影别名、字符串函数 UPPER/CONCAT、窗口函数 ROW_NUMBER、聚合函数 COUNT/AVG、
     *       LEFT JOIN、复杂嵌套 WHERE 逻辑组、IN 子查询、EXISTS/NOT EXISTS 关联子查询、BETWEEN、IS NOT NULL、
     *       GROUP BY 多列、HAVING 复合过滤、多列 ORDER BY、LIMIT / OFFSET 分页。
     */
    @Test
    public void testKitchenSinkComplexQuery() {
        Student s = orm.proxy(Student.class);
        Teacher t = orm.proxy(Teacher.class);

        Query<Student> query = orm.select(
                s.getId(),
                upper(s.getStudentName()).as("upper_name"),
                concat(s.getStudentName(), "_", s.getTeacher().getTitle()).as("full_title"),
                rowNumber().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rn"),
                count(s.getId()).as("group_cnt"),
                avg(s.getAge()).as("avg_age")
        ).from(Student.class);

        query.where()
                .and(s.getAge()).between(18, 30)
                .andGroup(g1 -> g1
                        .and(s.getStudentName()).like("学生%")
                        .orGroup(g2 -> g2
                                .and(s.getAge()).le(21)
                                .and(s.getTeacherId()).isNotNull()
                        )
                )
                .and(s.getTeacherId()).in(
                        orm.select(t.getId())
                           .from(Teacher.class)
                           .where()
                               .and(t.getAge()).ge(30)
                )
                .andExists(
                        orm.select(t.getId())
                           .from(Teacher.class)
                           .where()
                               .and(t.getId()).eq(s.getTeacherId())
                               .and(t.getTitle()).in("教授", "副教授")
                )
                .andNotExists(
                        orm.select(t.getId())
                           .from(Teacher.class)
                           .where()
                               .and(t.getId()).eq(s.getTeacherId())
                               .and(t.getTitle()).eq("助教")
                )
                .and(length(s.getStudentName())).ge(3)
                .and(s.getTeacherId()).isNotNull();

        query.groupBy(s.getId(), s.getStudentName(), s.getAge(), s.getTeacherId(), s.getTeacher().getTitle())
             .having()
                 .and(count(s.getId())).ge(1)
                 .or(avg(s.getAge())).gt(18)
             .orderBy(s.getAge()).desc()
             .orderBy(s.getId()).asc();

        query.limit(3).offset(0);

        String sql = query.toSql();
        // 验证各核心 SQL 语法节点结构完整性
        assertTrue("Must have SELECT columns", sql.contains("UPPER(t0.\"student_name\") AS \"upper_name\""));
        assertTrue("Must have CONCAT expression", sql.contains("t0.\"student_name\" || ? || t1.\"title\" AS \"full_title\""));
        assertTrue("Must have ROW_NUMBER window function", sql.contains("ROW_NUMBER() OVER (PARTITION BY t0.\"teacher_id\" ORDER BY t0.\"age\" ASC) AS \"rn\""));
        assertTrue("Must have LEFT JOIN", sql.contains("LEFT JOIN \"t_teacher\" t1 ON t0.\"teacher_id\" = t1.\"id\""));
        assertTrue("Must have logical delete check", sql.contains("t0.\"is_deleted\" = ?"));
        assertTrue("Must have IN subquery", sql.contains("IN (SELECT"));
        assertTrue("Must have EXISTS subquery", sql.contains("EXISTS (SELECT"));
        assertTrue("Must have NOT EXISTS subquery", sql.contains("NOT EXISTS (SELECT"));
        assertTrue("Must have GROUP BY", sql.contains("GROUP BY t0.\"id\", t0.\"student_name\", t0.\"age\", t0.\"teacher_id\", t1.\"title\""));
        assertTrue("Must have HAVING", sql.contains("HAVING COUNT(t0.\"id\") >= ? OR AVG(t0.\"age\") > ?"));
        assertTrue("Must have ORDER BY", sql.contains("ORDER BY t0.\"age\" DESC, t0.\"id\" ASC"));
        assertTrue("Must have OFFSET-FETCH paging", sql.contains("OFFSET ? ROWS FETCH NEXT ? ROWS ONLY"));

        // 执行查询并验证物理行结果
        List<Map<String, Object>> rows = query.listMaps();
        assertNotNull(rows);
        assertFalse(rows.isEmpty());
        assertTrue(rows.size() <= 3);

        Map<String, Object> firstRow = rows.get(0);
        assertNotNull(firstRow.get("upper_name"));
        assertNotNull(firstRow.get("full_title"));
        assertNotNull(firstRow.get("rn"));
    }

    /**
     * 2. 3 层深度嵌套关联子查询测试
     * 查询：找到指导导师有名下年龄 >= 24 岁学生的学生集合
     * 外层: Student t0
     * 第二层: EXISTS (Teacher t1 WHERE t1.id = t0.teacher_id AND ...)
     * 第三层: EXISTS (Student t2 WHERE t2.teacher_id = t1.id AND t2.age >= 24)
     */
    @Test
    public void testThreeLevelCorrelatedSubquery() {
        Student s0 = orm.proxy(Student.class);
        Teacher t1 = orm.proxy(Teacher.class);
        Student s2 = orm.proxy(Student.class);

        WhereBuilder<Student> query = orm.select(Student.class)
                .where()
                .andExists(
                        orm.select(t1.getId())
                           .from(Teacher.class)
                           .where()
                               .and(t1.getId()).eq(s0.getTeacherId())
                               .andExists(
                                       orm.select(s2.getId())
                                          .from(Student.class)
                                          .where()
                                              .and(s2.getTeacherId()).eq(t1.getId())
                                              .and(s2.getAge()).ge(24)
                               )
                )
                .orderBy(s0.getId()).asc();

        String sql = query.toSql();
        assertTrue(sql.contains("FROM \"t_student\" t0"));
        assertTrue(sql.contains("EXISTS (SELECT"));
        assertTrue(sql.contains("FROM \"t_teacher\" t1"));
        assertTrue(sql.contains("t1.\"id\" = t0.\"teacher_id\""));

        // 执行查询：张教授名下有学生C(24岁)，因此张教授名下的未删除学生(学生A, 学生B, 学生C)符合条件
        List<Student> results = query.list();
        assertEquals(3, results.size());
        assertEquals("学生A", results.get(0).getStudentName());
        assertEquals("学生B", results.get(1).getStudentName());
        assertEquals("学生C", results.get(2).getStudentName());
    }

    /**
     * 3. 复杂 UNION ALL 组合聚合、多表连接与过滤测试
     */
    @Test
    public void testComplexUnionAllWithAggregatesAndJoins() {
        Student s = orm.proxy(Student.class);

        // q1: 资深教师组（年龄>=35），按教师统计学生人数及平均年龄，要求学生数 >= 2
        Query<Student> q1 = orm.select(
                s.getTeacherId(),
                count(s.getId()).as("total"),
                avg(s.getAge()).as("mean_age")
        ).from(Student.class);
        q1.where()
                .and(s.getTeacherId()).isNotNull()
                .and(s.getTeacher().getAge()).ge(35);
        q1.groupBy(s.getTeacherId())
          .having().and(count(s.getId())).ge(2);

        // q2: 年轻教师组（年龄<35），按教师统计学生人数，要求学生数 >= 1
        Query<Student> q2 = orm.select(
                s.getTeacherId(),
                count(s.getId()).as("total"),
                avg(s.getAge()).as("mean_age")
        ).from(Student.class);
        q2.where()
                .and(s.getTeacherId()).isNotNull()
                .and(s.getTeacher().getAge()).lt(35);
        q2.groupBy(s.getTeacherId())
          .having().and(count(s.getId())).ge(1);

        // 联合查询
        List<Map<String, Object>> unionResult = q1.unionAll(q2).listMaps();

        assertNotNull(unionResult);
        // q1 命中了 t1(张教授 3人) 和 t2(李副教授 2人); q2 命中了 t3(王讲师 1人)，总计 3 组
        assertEquals(3, unionResult.size());
    }

