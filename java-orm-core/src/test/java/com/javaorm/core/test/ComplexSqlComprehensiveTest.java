    private List<Student> executeDynamicSearch(
            String keyword,
            Integer minAge,
            Integer maxAge,
            List<String> teacherTitles,
            Boolean hasTeacher,
            String sortBy,
            String sortDir) {

        Student s = orm.proxy(Student.class);
        WhereBuilder<Student> w = orm.select(Student.class).where();

        if (keyword != null && !keyword.isEmpty()) {
            w.andGroup((g, stu) -> g
                    .or(stu.getStudentName()).like("%" + keyword + "%")
                    .or(stu.getTeacher().getTeacherName()).like("%" + keyword + "%")
            );
        }

        if (minAge != null && maxAge != null) {
            w.and(s.getAge()).between(minAge, maxAge);
        } else if (minAge != null) {
            w.and(s.getAge()).ge(minAge);
        } else if (maxAge != null) {
            w.and(s.getAge()).le(maxAge);
        }

        if (teacherTitles != null && !teacherTitles.isEmpty()) {
            w.and(s.getTeacher().getTitle()).in(teacherTitles);
        }

        if (hasTeacher != null) {
            if (hasTeacher) {
                w.and(s.getTeacherId()).isNotNull();
            } else {
                w.and(s.getTeacherId()).isNull();
            }
        }

        if ("age".equalsIgnoreCase(sortBy)) {
            if ("DESC".equalsIgnoreCase(sortDir)) {
                w.orderBy(s.getAge()).desc();
            } else {
                w.orderBy(s.getAge()).asc();
            }
        } else {
            w.orderBy(s.getId()).asc();
        }

        return w.list();
    }

