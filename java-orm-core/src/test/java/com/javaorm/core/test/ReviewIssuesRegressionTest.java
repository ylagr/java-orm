    // 4. [P1／功能缺口] 多租户完整隔离测试 (SELECT, INSERT, UPDATE, DELETE)
    // ---------------------------------------------------------------------------------
    @Test
    public void testMultiTenancyIsolation() {
        // 1. 租户 100 插入数据
        TenantContext.setTenantId(100L);
        TenantDocument doc1 = new TenantDocument();
        doc1.setTitle("Tenant 100 Document 1");
        doc1.setContent("Secret 100");
        orm.insert(doc1);
        assertNotNull("Generated PK should be backfilled", doc1.getId());
        assertEquals(Long.valueOf(100L), doc1.getTenantId()); // 自动填充

        TenantDocument doc2 = new TenantDocument();
        doc2.setTitle("Tenant 100 Document 2");
        doc2.setContent("Secret 100-2");
        orm.insert(doc2);

        // 2. 租户 200 插入数据
        TenantContext.setTenantId(200L);
        TenantDocument doc3 = new TenantDocument();
        doc3.setTitle("Tenant 200 Document");
        doc3.setContent("Secret 200");
        orm.insert(doc3);
        assertEquals(Long.valueOf(200L), doc3.getTenantId());

        // 3. 租户 100 查询：仅能查到租户 100 的两条数据
        TenantContext.setTenantId(100L);
        List<TenantDocument> list100 = orm.select(TenantDocument.class).list();
        assertEquals(2, list100.size());
        for (TenantDocument d : list100) {
            assertEquals(Long.valueOf(100L), d.getTenantId());
        }

        // 4. 租户 100 更新：尝试更新 doc3 (属于租户200)，应当受阻影响 0 行
        int affected = orm.update(TenantDocument.class)
                .set(TenantDocument::getTitle, "Hacked Title")
                .where().and(TenantDocument::getId).eq(doc3.getId())
                .execute();
        assertEquals("Cannot update other tenant data", 0, affected);

        // 5. 租户 100 删除：尝试删除 doc3，影响 0 行
        int deleted = orm.delete(TenantDocument.class)
                .where().and(TenantDocument::getId).eq(doc3.getId())
                .execute();
        assertEquals("Cannot delete other tenant data", 0, deleted);

        // 6. 租户 200 查询：仅能查到一条
        TenantContext.setTenantId(200L);
        List<TenantDocument> list200 = orm.select(TenantDocument.class).list();
        assertEquals(1, list200.size());
        assertEquals("Secret 200", list200.get(0).getContent());
    }

