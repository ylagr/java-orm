    // 1. [P1] 顶层 OR 不能绕过自动逻辑删除过滤
    // ---------------------------------------------------------------------------------
    @Test
    public void testTopLevelOrDoesNotBypassLogicalDelete() {
        // 用户顶层使用 OR 条件：.and(age >= 18).or(studentName = 'DeletedTarget')
        WhereBuilder<Student> query = orm.select(Student.class)
                .where()
                .and(Student::getAge).ge(18)
                .or(Student::getStudentName).eq("DeletedTarget");

        SqlAndParams sp = query.toSqlAndParams();
        String sql = sp.getSql();

        // 验证系统条件与用户条件隔离，形成 WHERE is_deleted = ? AND (age >= ? OR student_name = ?)
        assertTrue("SQL must isolate system condition from user OR group: " + sql,
                sql.contains("WHERE t0.\"is_deleted\" = ? AND (t0.\"age\" >= ? OR t0.\"student_name\" = ?)"));

        // 实测执行：已逻辑删除的 DeletedTarget 绝对不能被查出！
        List<Student> list = query.list();
        for (Student s : list) {
            assertEquals("Must not contain deleted student", 0, (int) s.getIsDeleted());
            assertNotEquals("DeletedTarget must NOT be queried even with OR", "DeletedTarget", s.getStudentName());
        }
        assertEquals(4, list.size());
    }

