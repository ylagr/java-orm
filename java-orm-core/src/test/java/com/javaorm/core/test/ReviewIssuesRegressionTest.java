    @Test
    public void testIncludeChunkingForLargeCollections() {
        // 创建大量学生记录（例如 550 条），关联到 teacher 1
        List<Student> largeList = new ArrayList<>();
        for (int i = 0; i < 550; i++) {
            Student s = new Student();
            s.setId((long) (1000 + i));
            s.setStudentName("BulkStudent" + i);
            s.setTeacherId(1L);
            largeList.add(s);
        }

        // 测试包含 teacher（ManyToOne 分片批量装配）
        com.javaorm.core.query.Query<Student> query = orm.select(Student.class)
                .include(Student::getTeacher);

        try (Connection conn = dataSource.getConnection()) {
            com.javaorm.core.hydration.IncludeProcessor.processIncludes(
                    conn,
                    largeList,
                    EntityMetadataManager.get(Student.class, orm.getConfig()),
                    query.getIncludeSpecs(),
                    orm.getDialect(),
                    orm.getConfig(),
                    dataSource
            );
        } catch (Exception e) {
            fail("Include chunking should not fail: " + e.getMessage());
        }

        // 验证所有 550 个实体都被正确回填了老师对象
        for (Student s : largeList) {
            assertNotNull("Teacher should be hydrated for student " + s.getId(), s.getTeacher());
            assertEquals("张老师", s.getTeacher().getTeacherName());
        }
    }

