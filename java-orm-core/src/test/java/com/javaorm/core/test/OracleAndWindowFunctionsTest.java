/**
 * Oracle 方言与全量开窗函数测试套件。
 * 基于本地零依赖的 H2 (Oracle 兼容模式) 运行验证。
 */
public class OracleAndWindowFunctionsTest {

    private JavaOrm orm;
    private JdbcDataSource dataSource;

    @Before
    public void setUp() throws Exception {
        RecordingContext.clear();

        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:test_oracle;MODE=Oracle;DEFAULT_NULL_ORDERING=HIGH;DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        dataSource.setPassword("");

        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS \"t_student\"");
            stmt.execute("DROP TABLE IF EXISTS \"t_teacher\"");

            stmt.execute("CREATE TABLE \"t_teacher\" (" +
                    "\"id\" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "\"teacher_name\" VARCHAR2(100), " +
                    "\"age\" NUMBER(10), " +
                    "\"title\" VARCHAR2(100));");

            stmt.execute("CREATE TABLE \"t_student\" (" +
                    "\"id\" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "\"student_name\" VARCHAR2(100), " +
                    "\"age\" NUMBER(10), " +
                    "\"teacher_id\" NUMBER(19), " +
                    "\"is_deleted\" NUMBER(1) DEFAULT 0, " +
                    "\"create_time\" TIMESTAMP);");
        }

        OrmConfig config = new OrmConfig().setPrintSql(true);
        orm = JavaOrm.create(dataSource, new OracleDialect(), config);

        // 初始化基础测试数据
        Teacher t1 = new Teacher();
        t1.setTeacherName("Prof. Smith");
        t1.setAge(45);
        t1.setTitle("Professor");
        orm.insert(t1);

        Teacher t2 = new Teacher();
        t2.setTeacherName("Dr. Johnson");
        t2.setAge(38);
        t2.setTitle("Associate Professor");
        orm.insert(t2);

        // Teacher 1 组学生
        insertStudent("Alice", 20, t1.getId());
        insertStudent("Bob", 22, t1.getId());
        insertStudent("Charlie", 22, t1.getId());
        insertStudent("David", 25, t1.getId());

        // Teacher 2 组学生
        insertStudent("Eve", 19, t2.getId());
        insertStudent("Frank", 21, t2.getId());
    }

    private void insertStudent(String name, int age, Long teacherId) {
        Student s = new Student();
        s.setStudentName(name);
        s.setAge(age);
        s.setTeacherId(teacherId);
        s.setIsDeleted(0);
        s.setCreateTime(LocalDateTime.now());
        orm.insert(s);
    }

    @After
    public void tearDown() {
        RecordingContext.clear();
    }

    /**
     * 1. 测试所有排名类开窗函数：
     * ROW_NUMBER(), RANK(), DENSE_RANK(), PERCENT_RANK(), CUME_DIST(), NTILE(n)
     */
    @Test
    public void testRankingWindowFunctions() {
        Student s = proxy(Student.class);

        List<Map<String, Object>> list = orm.select(Student.class).select(
                s.getId(),
                s.getStudentName(),
                s.getAge(),
                s.getTeacherId(),
                rowNumber().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rn"),
                rank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rk"),
                denseRank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("drk"),
                ntile(2).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("nt"),
                percentRank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("pr"),
                cumeDist().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("cd")
        ).where(w -> w.and(s.getTeacherId()).eq(1L))
         .orderBy(s.getAge()).asc()
         .orderBy(s.getId()).asc()
         .maps();

        assertEquals(4, list.size());

        // Alice (age 20)
        Map<String, Object> r1 = list.get(0);
        assertEquals("Alice", r1.get("student_name"));
        assertEquals(1L, ((Number) r1.get("rn")).longValue());
        assertEquals(1L, ((Number) r1.get("rk")).longValue());
        assertEquals(1L, ((Number) r1.get("drk")).longValue());
        assertEquals(1, ((Number) r1.get("nt")).intValue());

        // Bob (age 22) - 同年龄第 1 人
        Map<String, Object> r2 = list.get(1);
        assertEquals("Bob", r2.get("student_name"));
        assertEquals(2L, ((Number) r2.get("rn")).longValue());
        assertEquals(2L, ((Number) r2.get("rk")).longValue());
        assertEquals(2L, ((Number) r2.get("drk")).longValue());
        assertEquals(1, ((Number) r2.get("nt")).intValue());

        // Charlie (age 22) - 同年龄第 2 人
        Map<String, Object> r3 = list.get(2);
        assertEquals("Charlie", r3.get("student_name"));
        assertEquals(3L, ((Number) r3.get("rn")).longValue());
        assertEquals(2L, ((Number) r3.get("rk")).longValue()); // 并列第 2
        assertEquals(2L, ((Number) r3.get("drk")).longValue());
        assertEquals(2, ((Number) r3.get("nt")).intValue());

        // David (age 25)
        Map<String, Object> r4 = list.get(3);
        assertEquals("David", r4.get("student_name"));
        assertEquals(4L, ((Number) r4.get("rn")).longValue());
        assertEquals(4L, ((Number) r4.get("rk")).longValue()); // 跳过 3 -> 4
        assertEquals(3L, ((Number) r4.get("drk")).longValue()); // 密集排名 -> 3
        assertEquals(2, ((Number) r4.get("nt")).intValue());
    }

    /**
     * 2. 测试位移/取值开窗函数：
     * LEAD(), LAG(), FIRST_VALUE(), LAST_VALUE(), NTH_VALUE()
     */
    @Test
    public void testValueWindowFunctions() {
        Student s = proxy(Student.class);

        List<Map<String, Object>> list = orm.select(Student.class).select(
                s.getId(),
                s.getStudentName(),
                s.getAge(),
                lead(s.getAge(), 1, 0).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().orderBy(s.getId()).asc().as("next_age"),
                lag(s.getAge(), 1, 0).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().orderBy(s.getId()).asc().as("prev_age"),
                firstValue(s.getAge()).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().orderBy(s.getId()).asc().as("first_age")
        ).where(w -> w.and(s.getTeacherId()).eq(1L))
         .orderBy(s.getAge()).asc()
         .orderBy(s.getId()).asc()
         .maps();

        assertEquals(4, list.size());

        // Alice (age 20) -> prev: 0, next: 22, first: 20
        Map<String, Object> r1 = list.get(0);
        assertEquals(0, ((Number) r1.get("prev_age")).intValue());
        assertEquals(22, ((Number) r1.get("next_age")).intValue());
        assertEquals(20, ((Number) r1.get("first_age")).intValue());

        // David (age 25) -> prev: 22, next: 0 (default), first: 20
        Map<String, Object> r4 = list.get(3);
        assertEquals(22, ((Number) r4.get("prev_age")).intValue());
        assertEquals(0, ((Number) r4.get("next_age")).intValue());
        assertEquals(20, ((Number) r4.get("first_age")).intValue());
    }

    /**
     * 3. 测试聚合开窗函数及开窗滑动范围 (ROWS BETWEEN)：
     * SUM().over(), AVG().over(), COUNT().over(), MIN().over(), MAX().over()
     */
    @Test
    public void testAggregateWindowFunctionsAndFrames() {
        Student s = proxy(Student.class);

        List<Map<String, Object>> list = orm.select(Student.class).select(
                s.getId(),
                s.getStudentName(),
                s.getAge(),
                sum(s.getAge()).over().partitionBy(s.getTeacherId()).as("dept_sum"),
                avg(s.getAge()).over().partitionBy(s.getTeacherId()).as("dept_avg"),
                min(s.getAge()).over().partitionBy(s.getTeacherId()).as("dept_min"),
                max(s.getAge()).over().partitionBy(s.getTeacherId()).as("dept_max"),
                // 累计求和滑动窗口: ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
                sum(s.getAge()).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().rowsUnboundedPreceding().as("running_sum"),
                // 全表无 PARTITION 开窗统计
                count().over().as("grand_count")
        ).where(w -> w.and(s.getTeacherId()).eq(1L))
         .orderBy(s.getAge()).asc()
         .orderBy(s.getId()).asc()
         .maps();

        assertEquals(4, list.size());

        // 总和: 20 + 22 + 22 + 25 = 89
        for (Map<String, Object> r : list) {
            assertEquals(89, ((Number) r.get("dept_sum")).intValue());
            assertEquals(20, ((Number) r.get("dept_min")).intValue());
            assertEquals(25, ((Number) r.get("dept_max")).intValue());
            assertEquals(4L, ((Number) r.get("grand_count")).longValue());
        }

        // 验证累计求和
        assertEquals(20, ((Number) list.get(0).get("running_sum")).intValue()); // 20
        assertEquals(42, ((Number) list.get(1).get("running_sum")).intValue()); // 20 + 22
        assertEquals(64, ((Number) list.get(2).get("running_sum")).intValue()); // 20 + 22 + 22
        assertEquals(89, ((Number) list.get(3).get("running_sum")).intValue()); // 20 + 22 + 22 + 25
    }

    /**
     * 4. 测试 Oracle 方言专属特性：
     * 12c+ 分页 (OFFSET ? ROWS FETCH NEXT ? ROWS ONLY)、SYSDATE、NVL、|| 拼接
     */
    @Test
    public void testOracleDialectFeatures() {
        Student s = proxy(Student.class);

        // 分页测试: 第 1 页 2 条
        List<Student> page1 = orm.select(Student.class)
                .orderBy(s.getId()).asc()
                .page(1, 2)
                .list();
        assertEquals(2, page1.size());
        assertEquals("Alice", page1.get(0).getStudentName());
        assertEquals("Bob", page1.get(1).getStudentName());

        // 分页测试: 第 2 页 2 条
        List<Student> page2 = orm.select(Student.class)
                .orderBy(s.getId()).asc()
                .page(2, 2)
                .list();
        assertEquals(2, page2.size());
        assertEquals("Charlie", page2.get(0).getStudentName());
        assertEquals("David", page2.get(1).getStudentName());

        // 函数测试: ifNull (NVL), now (SYSDATE), concat (||)
        List<Map<String, Object>> funcList = orm.select(Student.class).select(
                s.getId(),
                ifNull(s.getStudentName(), "NONAME").as("safe_name"),
                concat(s.getStudentName(), raw("' ('"), s.getAge(), raw("')'")).as("display_info"),
                now().as("cur_time")
        ).where(w -> w.and(s.getId()).eq(page1.get(0).getId()))
         .maps();

        assertEquals(1, funcList.size());
        assertEquals("Alice", funcList.get(0).get("safe_name"));
        assertEquals("Alice (20)", funcList.get(0).get("display_info"));
        assertNotNull(funcList.get(0).get("cur_time"));
    }

    /**
     * 5. 测试 DTO 投影映射开窗函数结果：
     * 自动映射到 StudentWindowDto 的对应字段中
     */
    @Test
    public void testDtoProjectionWithWindowFunctions() {
        Student s = proxy(Student.class);

        List<StudentWindowDto> dtoList = orm.select(StudentWindowDto.class).from(Student.class).select(
                s.getId(),
                s.getStudentName(),
                s.getAge(),
                s.getTeacherId(),
                rowNumber().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rowNum"),
                rank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("rankVal"),
                denseRank().over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("denseRankVal"),
                ntile(2).over().partitionBy(s.getTeacherId()).orderBy(s.getAge()).asc().as("ntileVal"),
                sum(s.getAge()).over().partitionBy(s.getTeacherId()).as("sumAge")
        ).where(w -> w.and(s.getTeacherId()).eq(1L))
         .orderBy(s.getId()).asc()
         .list();

        assertEquals(4, dtoList.size());

        StudentWindowDto d1 = dtoList.get(0);
        assertEquals("Alice", d1.getStudentName());
        assertEquals(Long.valueOf(1), d1.getRowNum());
        assertEquals(Long.valueOf(1), d1.getRankVal());
        assertEquals(Long.valueOf(1), d1.getDenseRankVal());
        assertEquals(Integer.valueOf(1), d1.getNtileVal());
        assertEquals(Integer.valueOf(89), d1.getSumAge());

        StudentWindowDto d4 = dtoList.get(3);
        assertEquals("David", d4.getStudentName());
        assertEquals(Long.valueOf(4), d4.getRowNum());
        assertEquals(Long.valueOf(4), d4.getRankVal());
        assertEquals(Long.valueOf(3), d4.getDenseRankVal());
        assertEquals(Integer.valueOf(2), d4.getNtileVal());
        assertEquals(Integer.valueOf(89), d4.getSumAge());
    }
}
