package com.javaorm.core.codefirst;

import com.javaorm.core.dialect.*;
import com.javaorm.core.metadata.ColumnMetadata;
import com.javaorm.core.metadata.EntityMetadata;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.util.*;

/**
 * 跨数据库方言 DDL 语句构造器（支持 MySQL, PostgreSQL, H2, SQLite, Oracle 等）。
 */
public class DdlBuilder {

    public static String buildCreateTable(Dialect dialect, EntityMetadata metadata) {
        StringBuilder sb = new StringBuilder();
        String tableName = dialect.quote(metadata.getTableName());
        sb.append("CREATE TABLE ").append(tableName).append(" (\n");

        boolean isMysql = isMySQL(dialect);
        boolean isPg = isPostgreSQL(dialect);
        boolean isH2 = isH2(dialect);
        boolean isSqlite = isSQLite(dialect);
        boolean isOracle = isOracle(dialect);

        List<String> colDefs = new ArrayList<>();
        List<String> pkCols = new ArrayList<>();

        for (ColumnMetadata col : metadata.getColumns()) {
            if (col.isIgnored()) continue;
            StringBuilder colSb = new StringBuilder("  ");
            String colName = dialect.quote(col.getColumnName());
            colSb.append(colName).append(" ");

            String colType = getColumnType(dialect, col);
            colSb.append(colType);

            if (col.isPrimaryKey()) {
                pkCols.add(colName);
                if (isSqlite && col.isGenerated()) {
                    // SQLite 的自增主键已内联在字段定义中 (INTEGER PRIMARY KEY AUTOINCREMENT)
                } else if (isPg && col.isGenerated()) {
                    // PG BIGSERIAL / SERIAL 自带 PRIMARY KEY
                } else if (isH2 && col.isGenerated()) {
                    // H2 AUTO_INCREMENT PRIMARY KEY
                } else if (isOracle && col.isGenerated()) {
                    // Oracle GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                }
            } else {
                if (!col.isNullable()) {
                    colSb.append(" NOT NULL");
                }
                if (col.getDefaultValue() != null && !col.getDefaultValue().isEmpty()) {
                    colSb.append(" DEFAULT ").append(col.getDefaultValue());
                }
            }

            // 列级注释 (MySQL 支持)
            if (isMysql && col.getComment() != null && !col.getComment().isEmpty()) {
                colSb.append(" COMMENT '").append(escapeSql(col.getComment())).append("'");
            }

            colDefs.add(colSb.toString());
        }

        // 追加表级主键约束（针对非内联主键或 MySQL 复合主键）
        if (!pkCols.isEmpty()) {
            if (isMysql || (!isSqlite && !isPg && !isH2 && !isOracle)) {
                colDefs.add("  PRIMARY KEY (" + String.join(", ", pkCols) + ")");
            } else if ((isPg || isH2 || isOracle) && metadata.getIdColumn() != null && !metadata.getIdColumn().isGenerated()) {
                colDefs.add("  PRIMARY KEY (" + String.join(", ", pkCols) + ")");
            }
        }

        sb.append(String.join(",\n", colDefs));
        sb.append("\n)");

        // 表级参数与注释 (MySQL)
        if (isMysql) {
            sb.append(" ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
            if (metadata.getComment() != null && !metadata.getComment().isEmpty()) {
                sb.append(" COMMENT='").append(escapeSql(metadata.getComment())).append("'");
            }
        }

        return sb.toString();
    }

    public static String buildAddColumn(Dialect dialect, EntityMetadata metadata, ColumnMetadata column) {
        StringBuilder sb = new StringBuilder();
        String tableName = dialect.quote(metadata.getTableName());
        String colName = dialect.quote(column.getColumnName());
        String colType = getColumnType(dialect, column);

        if (isOracle(dialect)) {
            sb.append("ALTER TABLE ").append(tableName).append(" ADD (").append(colName).append(" ").append(colType);
            if (!column.isNullable()) {
                sb.append(" NOT NULL");
            }
            if (column.getDefaultValue() != null && !column.getDefaultValue().isEmpty()) {
                sb.append(" DEFAULT ").append(column.getDefaultValue());
            }
            sb.append(")");
            return sb.toString();
        }

        sb.append("ALTER TABLE ").append(tableName).append(" ADD COLUMN ").append(colName).append(" ").append(colType);

        if (!isSQLite(dialect)) {
            if (!column.isNullable()) {
                sb.append(" NOT NULL");
            }
            if (column.getDefaultValue() != null && !column.getDefaultValue().isEmpty()) {
                sb.append(" DEFAULT ").append(column.getDefaultValue());
            }
            if (isMySQL(dialect) && column.getComment() != null && !column.getComment().isEmpty()) {
                sb.append(" COMMENT '").append(escapeSql(column.getComment())).append("'");
            }
        }

        return sb.toString();
    }

    public static String buildDropTable(Dialect dialect, String tableName) {
        String quoted = dialect.quote(tableName);
        if (isOracle(dialect)) {
            return "DROP TABLE " + quoted + " CASCADE CONSTRAINTS";
        }
        return "DROP TABLE IF EXISTS " + quoted;
    }

    public static String getColumnType(Dialect dialect, ColumnMetadata col) {
        if (col.getColumnDefinition() != null && !col.getColumnDefinition().trim().isEmpty()) {
            return col.getColumnDefinition().trim();
        }

        Class<?> type = col.getPropertyType();
        boolean isPk = col.isPrimaryKey();
        boolean isGen = col.isGenerated();

        boolean isMysql = isMySQL(dialect);
        boolean isPg = isPostgreSQL(dialect);
        boolean isH2 = isH2(dialect);
        boolean isSqlite = isSQLite(dialect);
        boolean isOracle = isOracle(dialect);

        // 1. 主键自增
        if (isPk && isGen) {
            if (isMysql) {
                return (type == Integer.class || type == int.class) ? "INT NOT NULL AUTO_INCREMENT" : "BIGINT NOT NULL AUTO_INCREMENT";
            }
            if (isPg) {
                return (type == Integer.class || type == int.class) ? "SERIAL PRIMARY KEY" : "BIGSERIAL PRIMARY KEY";
            }
            if (isH2) {
                return (type == Integer.class || type == int.class) ? "INT NOT NULL AUTO_INCREMENT PRIMARY KEY" : "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY";
            }
            if (isSqlite) {
                return "INTEGER PRIMARY KEY AUTOINCREMENT";
            }
            if (isOracle) {
                return (type == Integer.class || type == int.class) ? "NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
            }
        }

        // 2. 整型
        if (type == Long.class || type == long.class) {
            return isOracle ? "NUMBER(19)" : "BIGINT";
        }
        if (type == Integer.class || type == int.class) {
            return isOracle ? "NUMBER(10)" : "INT";
        }
        if (type == Short.class || type == short.class) {
            return isOracle ? "NUMBER(6)" : "SMALLINT";
        }
        if (type == Byte.class || type == byte.class) {
            return isOracle ? "NUMBER(3)" : "TINYINT";
        }

        // 3. 浮点/定点
        if (type == BigDecimal.class) {
            int p = col.getPrecision() > 0 ? col.getPrecision() : 18;
            int s = col.getScale() > 0 ? col.getScale() : 4;
            return isOracle ? "NUMBER(" + p + ", " + s + ")" : "DECIMAL(" + p + ", " + s + ")";
        }
        if (type == Double.class || type == double.class) {
            if (isPg) return "DOUBLE PRECISION";
            if (isOracle) return "FLOAT";
            return "DOUBLE";
        }
        if (type == Float.class || type == float.class) {
            return "FLOAT";
        }

        // 4. 布尔
        if (type == Boolean.class || type == boolean.class) {
            if (isPg || isH2) return "BOOLEAN";
            if (isOracle) return "NUMBER(1)";
            return "TINYINT(1)";
        }

        // 5. 日期时间
        if (type == LocalDateTime.class || type == java.util.Date.class || type == java.sql.Timestamp.class) {
            if (isMysql) return "DATETIME";
            return "TIMESTAMP";
        }
        if (type == LocalDate.class || type == java.sql.Date.class) {
            return "DATE";
        }
        if (type == LocalTime.class || type == java.sql.Time.class) {
            return isOracle ? "TIMESTAMP" : "TIME";
        }

        // 6. 二进制
        if (type == byte[].class) {
            if (isMysql) return "LONGBLOB";
            if (isPg) return "BYTEA";
            return "BLOB";
        }

        // 7. 枚举
        if (type.isEnum()) {
            return "VARCHAR(50)";
        }

        // 8. 字符串 / 默认
        if (type == String.class) {
            int len = col.getLength() > 0 ? col.getLength() : 255;
            if (len > 65535) {
                if (isOracle || isH2) return "CLOB";
                return "TEXT";
            }
            if (isOracle) return "VARCHAR2(" + len + ")";
            if (isSqlite) return "TEXT";
            return "VARCHAR(" + len + ")";
        }

        return "VARCHAR(255)";
    }

    private static boolean isMySQL(Dialect dialect) {
        return dialect instanceof MySQLDialect || dialect.getClass().getSimpleName().toLowerCase().contains("mysql");
    }

    private static boolean isPostgreSQL(Dialect dialect) {
        return dialect instanceof PostgreSQLDialect || dialect.getClass().getSimpleName().toLowerCase().contains("postgres");
    }

    private static boolean isH2(Dialect dialect) {
        return dialect instanceof H2Dialect || dialect.getClass().getSimpleName().toLowerCase().contains("h2");
    }

    private static boolean isSQLite(Dialect dialect) {
        return dialect instanceof SQLiteDialect || dialect.getClass().getSimpleName().toLowerCase().contains("sqlite");
    }

    private static boolean isOracle(Dialect dialect) {
        return dialect instanceof OracleDialect || dialect.getClass().getSimpleName().toLowerCase().contains("oracle");
    }

    private static String escapeSql(String val) {
        if (val == null) return "";
        return val.replace("'", "''");
    }

    /**
     * 去除默认值中的冗余字符（首尾单双引号、PostgreSQL类型后缀如 ::text、MySQL外层括号等），以便精准对比差异
     */
    public static String normalizeDefaultValue(String val) {
        if (val == null) return null;
        String s = val.trim();
        // 处理 PostgreSQL 类型后缀，如 'foo'::character varying 或 '1'::integer
        int castIdx = s.indexOf("::");
        if (castIdx > 0) {
            s = s.substring(0, castIdx).trim();
        }
        // 处理 MySQL / H2 括号，如 ((1)) 或 (1)
        while (s.startsWith("(") && s.endsWith(")") && s.length() >= 2) {
            s = s.substring(1, s.length() - 1).trim();
        }
        // 处理包围的单引号或双引号
        if ((s.startsWith("'") && s.endsWith("'")) || (s.startsWith("\"") && s.endsWith("\""))) {
            if (s.length() >= 2) {
                s = s.substring(1, s.length() - 1);
            }
        }
        return s.trim();
    }

    /**
     * 字段差异描述符
     */
    public static class ColumnDiff {
        private boolean lengthChanged;
        private boolean precisionChanged;
        private boolean scaleChanged;
        private boolean defaultValueChanged;
        private boolean nullableChanged;
        private boolean typeChanged;
        private boolean commentChanged;

        public boolean hasChange() {
            return lengthChanged || precisionChanged || scaleChanged
                    || defaultValueChanged || nullableChanged || typeChanged || commentChanged;
        }

        public boolean isLengthChanged() {
            return lengthChanged;
        }

        public void setLengthChanged(boolean lengthChanged) {
            this.lengthChanged = lengthChanged;
        }

        public boolean isPrecisionChanged() {
            return precisionChanged;
        }

        public void setPrecisionChanged(boolean precisionChanged) {
            this.precisionChanged = precisionChanged;
        }

        public boolean isScaleChanged() {
            return scaleChanged;
        }

        public void setScaleChanged(boolean scaleChanged) {
            this.scaleChanged = scaleChanged;
        }

        public boolean isDefaultValueChanged() {
            return defaultValueChanged;
        }

        public void setDefaultValueChanged(boolean defaultValueChanged) {
            this.defaultValueChanged = defaultValueChanged;
        }

        public boolean isNullableChanged() {
            return nullableChanged;
        }

        public void setNullableChanged(boolean nullableChanged) {
            this.nullableChanged = nullableChanged;
        }

        public boolean isTypeChanged() {
            return typeChanged;
        }

        public void setTypeChanged(boolean typeChanged) {
            this.typeChanged = typeChanged;
        }

        public boolean isCommentChanged() {
            return commentChanged;
        }

        public void setCommentChanged(boolean commentChanged) {
            this.commentChanged = commentChanged;
        }
    }

    /**
     * 对比实体定义与物理库列的差异（检测长度、精度、默认值、可空性等）
     */
    public static ColumnDiff diffColumn(Dialect dialect, ColumnMetadata col, PhysicalColumnDesc existing) {
        ColumnDiff diff = new ColumnDiff();
        if (col == null || existing == null) {
            return diff;
        }
        if (col.isPrimaryKey()) {
            return diff; // 主键列通常由自增或唯一索引管理，不随意执行结构微调
        }

        // 1. 字段长度变更检测（针对 String/字符类型）
        if (col.getPropertyType() == String.class) {
            int targetLength = col.getLength() > 0 ? col.getLength() : 255;
            int dbLength = existing.getColumnSize();
            if (dbLength > 0 && targetLength > 0 && dbLength != targetLength) {
                diff.setLengthChanged(true);
            }
        }

        // 2. 精度与标度变更检测（针对 BigDecimal）
        if (col.getPropertyType() == BigDecimal.class) {
            if (col.getPrecision() > 0 && existing.getColumnSize() > 0 && existing.getColumnSize() != col.getPrecision()) {
                diff.setPrecisionChanged(true);
            }
            if (col.getScale() >= 0 && existing.getDecimalDigits() != col.getScale()) {
                diff.setScaleChanged(true);
            }
        }

        // 3. 默认值变更检测
        if (col.getDefaultValue() != null && !col.getDefaultValue().trim().isEmpty()) {
            String targetDef = normalizeDefaultValue(col.getDefaultValue());
            String dbDef = normalizeDefaultValue(existing.getDefaultValue());
            if (dbDef == null || !targetDef.equalsIgnoreCase(dbDef)) {
                diff.setDefaultValueChanged(true);
            }
        }

        // 4. 可空性变更检测（实体要求 NOT NULL，但数据库允许 NULL）
        if (!col.isNullable() && existing.getNullable() == java.sql.DatabaseMetaData.columnNullable) {
            diff.setNullableChanged(true);
        }

        // 5. 自定义 columnDefinition 变更检测
        if (col.getColumnDefinition() != null && !col.getColumnDefinition().trim().isEmpty()) {
            String targetDef = col.getColumnDefinition().trim();
            if (existing.getTypeName() != null && !targetDef.equalsIgnoreCase(existing.getTypeName())) {
                diff.setTypeChanged(true);
            }
        }

        // 6. 注释变更检测
        if (col.getComment() != null && !col.getComment().trim().isEmpty()) {
            if (existing.getRemarks() == null || !existing.getRemarks().trim().equals(col.getComment().trim())) {
                diff.setCommentChanged(true);
            }
        }

        return diff;
    }

    /**
     * 生成变更已有字段属性的 DDL 语句（ALTER TABLE MODIFY/ALTER COLUMN）
     */
    public static List<String> buildAlterColumn(Dialect dialect, EntityMetadata metadata, ColumnMetadata column, PhysicalColumnDesc existing, ColumnDiff diff) {
        if (dialect == null || metadata == null || column == null || diff == null || !diff.hasChange()) {
            return Collections.emptyList();
        }
        if (isSQLite(dialect)) {
            // SQLite 存储层不强制类型长度且不支持 ALTER COLUMN，安全跳过
            return Collections.emptyList();
        }

        String tableName = dialect.quote(metadata.getTableName());
        String colName = dialect.quote(column.getColumnName());
        String colType = getColumnType(dialect, column);
        List<String> list = new ArrayList<>();

        if (isMySQL(dialect)) {
            // MySQL: ALTER TABLE `tbl` MODIFY COLUMN `col` colType [NOT NULL | NULL] [DEFAULT ...] [COMMENT '...']
            StringBuilder sb = new StringBuilder();
            sb.append("ALTER TABLE ").append(tableName).append(" MODIFY COLUMN ").append(colName).append(" ").append(colType);
            if (!column.isNullable()) {
                sb.append(" NOT NULL");
            } else {
                sb.append(" NULL");
            }
            if (column.getDefaultValue() != null && !column.getDefaultValue().trim().isEmpty()) {
                sb.append(" DEFAULT ").append(column.getDefaultValue().trim());
            }
            if (column.getComment() != null && !column.getComment().trim().isEmpty()) {
                sb.append(" COMMENT '").append(escapeSql(column.getComment().trim())).append("'");
            }
            list.add(sb.toString());
            return list;
        }

        if (isPostgreSQL(dialect)) {
            // PostgreSQL: ALTER TABLE "tbl" ALTER COLUMN "col" TYPE ... / SET DEFAULT ... / SET NOT NULL
            if (diff.isLengthChanged() || diff.isPrecisionChanged() || diff.isScaleChanged() || diff.isTypeChanged()) {
                list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " TYPE " + colType);
            }
            if (diff.isDefaultValueChanged() && column.getDefaultValue() != null && !column.getDefaultValue().trim().isEmpty()) {
                list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " SET DEFAULT " + column.getDefaultValue().trim());
            }
            if (diff.isNullableChanged()) {
                if (!column.isNullable()) {
                    list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " SET NOT NULL");
                } else {
                    list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " DROP NOT NULL");
                }
            }
            if (diff.isCommentChanged() && column.getComment() != null && !column.getComment().trim().isEmpty()) {
                list.add("COMMENT ON COLUMN " + tableName + "." + colName + " IS '" + escapeSql(column.getComment().trim()) + "'");
            }
            return list;
        }

        if (isH2(dialect)) {
            // H2: ALTER TABLE "tbl" ALTER COLUMN "col" SET DATA TYPE ... / SET DEFAULT ... / SET NOT NULL
            if (diff.isLengthChanged() || diff.isPrecisionChanged() || diff.isScaleChanged() || diff.isTypeChanged()) {
                list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " SET DATA TYPE " + colType);
            }
            if (diff.isDefaultValueChanged() && column.getDefaultValue() != null && !column.getDefaultValue().trim().isEmpty()) {
                list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " SET DEFAULT " + column.getDefaultValue().trim());
            }
            if (diff.isNullableChanged()) {
                if (!column.isNullable()) {
                    list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " SET NOT NULL");
                } else {
                    list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " DROP NOT NULL");
                }
            }
            if (diff.isCommentChanged() && column.getComment() != null && !column.getComment().trim().isEmpty()) {
                list.add("COMMENT ON COLUMN " + tableName + "." + colName + " IS '" + escapeSql(column.getComment().trim()) + "'");
            }
            return list;
        }

        if (isOracle(dialect)) {
            // Oracle: ALTER TABLE "tbl" MODIFY ("col" colType [DEFAULT ...] [NOT NULL | NULL])
            StringBuilder modifySb = new StringBuilder();
            modifySb.append("ALTER TABLE ").append(tableName).append(" MODIFY (").append(colName).append(" ").append(colType);
            if (diff.isDefaultValueChanged() && column.getDefaultValue() != null && !column.getDefaultValue().trim().isEmpty()) {
                modifySb.append(" DEFAULT ").append(column.getDefaultValue().trim());
            }
            if (diff.isNullableChanged()) {
                if (!column.isNullable()) {
                    modifySb.append(" NOT NULL");
                } else {
                    modifySb.append(" NULL");
                }
            }
            modifySb.append(")");
            list.add(modifySb.toString());

            if (diff.isCommentChanged() && column.getComment() != null && !column.getComment().trim().isEmpty()) {
                list.add("COMMENT ON COLUMN " + tableName + "." + colName + " IS '" + escapeSql(column.getComment().trim()) + "'");
            }
            return list;
        }

        // 默认 ANSI SQL 回退
        if (diff.isLengthChanged() || diff.isPrecisionChanged() || diff.isScaleChanged() || diff.isTypeChanged()) {
            list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " SET DATA TYPE " + colType);
        }
        if (diff.isDefaultValueChanged() && column.getDefaultValue() != null && !column.getDefaultValue().trim().isEmpty()) {
            list.add("ALTER TABLE " + tableName + " ALTER COLUMN " + colName + " SET DEFAULT " + column.getDefaultValue().trim());
        }
        return list;
    }
}
